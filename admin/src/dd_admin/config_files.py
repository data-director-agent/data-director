"""The deployment's settings files, as the configuration page shows them (deploy/README.md,
"Layout on the VM"). Secrets are never in these files, and the doctor reports one that is; a value
whose name says it is a secret is hidden here all the same."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from dd_admin.system import System

# A setting whose name says it holds a secret. One that ends in _FILE names where the secret is.
SECRET_NAME = re.compile(r"KEY|SECRET|TOKEN|PASSWORD|PASSWD|CREDENTIAL", re.IGNORECASE)
ASSIGNMENT = re.compile(r"^(\s*(?:export\s+)?)([A-Za-z_][A-Za-z0-9_]*)(\s*=\s*)(.*)$")
HIDDEN = "•••••• (hidden)"

APPLY = "sudo data-director apply"
RESTART = "sudo systemctl restart data-director.target"

# (file under /etc/data-director, what it is, how a change takes effect)
FILES: tuple[tuple[str, str, str], ...] = (
    (
        "deployment.yaml",
        "What this instance runs: its name, the orchestrator and any agents turned off",
        f"sudoedit /etc/data-director/deployment.yaml && {APPLY}",
    ),
    (
        "profile.yaml",
        "The institutional profile, generated by apply from deployment.yaml; do not edit it",
        APPLY,
    ),
    (
        "app.env",
        "The app's settings: sign-in, public URL, stores",
        f"sudoedit /etc/data-director/app.env && {RESTART}",
    ),
    (
        "workbench.env",
        "The workbench's settings, including its admins",
        "sudoedit /etc/data-director/workbench.env && "
        "sudo systemctl restart data-director-workbench",
    ),
    (
        "admin.env",
        "This service's own settings, if any",
        "sudoedit /etc/data-director/admin.env && sudo systemctl restart data-director-admin",
    ),
    (
        "agents.env",
        "Settings every agent shares",
        f"sudoedit /etc/data-director/agents.env && {RESTART}",
    ),
    (
        "deploy.env",
        "How the VM deploys: repository, branch, check, releases kept",
        "sudoedit /etc/data-director/deploy.env (read on the next pass)",
    ),
    (
        "backup.env",
        "Where backups go and how long they are kept",
        "sudoedit /etc/data-director/backup.env (read by the next backup)",
    ),
)


@dataclass(frozen=True)
class ConfigFile:
    name: str
    about: str
    change: str
    text: str | None  # None: missing, or this user may not read it


def redact(text: str) -> str:
    """`text`, an env file, with the value of every setting whose name names a secret hidden."""
    lines = []
    for line in text.splitlines():
        match = ASSIGNMENT.match(line)
        if match and not line.lstrip().startswith("#"):
            name, value = match.group(2), match.group(4)
            if value and SECRET_NAME.search(name) and not name.upper().endswith("_FILE"):
                line = f"{match.group(1)}{name}{match.group(3)}{HIDDEN}"
        lines.append(line)
    return "\n".join(lines)


def read(etc: Path | None, system: System) -> list[ConfigFile] | None:
    """Every settings file, with each agent's own after the shared ones; None if the settings
    directory is not configured."""
    if etc is None:
        return None
    found = [
        ConfigFile(name, about, change, _shown(etc / name, system)) for name, about, change in FILES
    ]
    for path in system.list_dir(etc / "agents") or []:
        if path.suffix == ".env":
            found.append(
                ConfigFile(
                    f"agents/{path.name}",
                    f"The {path.stem} agent's own settings",
                    f"sudoedit /etc/data-director/agents/{path.name} && "
                    f"sudo systemctl restart data-director-agent@{path.stem}",
                    _shown(path, system),
                )
            )
    return found


def _shown(path: Path, system: System) -> str | None:
    text = system.read_text(path)
    if text is None:
        return None
    return redact(text) if path.suffix == ".env" else text
