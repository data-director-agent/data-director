"""What every event mapping shares: what the log has said so far, and how a mapping says what an
event used and generated (docs/specs/provenance.md, The mapping)."""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from typing import Any

from dd_harness.provenance_graph.nodes import Graph, ref, uuid_iri

type Event = Mapping[str, Any]


@dataclass
class Context:
    """The graph being built, and what earlier events of the log said, oldest first."""

    graph: Graph
    project: str
    # The agent of each run, by invocation id.
    agents: dict[str, str] = field(default_factory=dict)
    inventory: str | None = None
    requirements: str | None = None
    # The researcher facts each person keeps, by ORCID iD.
    researchers: dict[str, str] = field(default_factory=dict)
    # Each version of each document, by (document id, version), as its event recorded it.
    versions: dict[tuple[str, int], Event] = field(default_factory=dict)
    latest: dict[str, int] = field(default_factory=dict)
    # The fact that stands for each (kind, subject), and each proposal by its event's id.
    facts: dict[tuple[str, str], str] = field(default_factory=dict)
    proposals: dict[str, str] = field(default_factory=dict)
    # The approval of each version approved, by (document id, version).
    approvals: dict[tuple[str, int], str] = field(default_factory=dict)
    # The approval each deposit was made under, by the approval's event id.
    deposit_approvals: dict[str, str] = field(default_factory=dict)


type Adds = Callable[[Context, str, Event], None]


def _nothing(ctx: Context, activity: str, event: Event) -> None:
    return None


@dataclass(frozen=True)
class EventMapping:
    """How one event type appears: its `dd:` class and what it adds to the common rule.
    `harness` says the harness carried the action out, for the principal; `generation` says the
    event names the generation of what a run produced, where a run caused it, rather than an
    activity of its own; `classify`, where given, gives the class of each event in place of
    `cls`."""

    cls: str
    adds: Adds = _nothing
    harness: bool = False
    generation: bool = False
    classify: Callable[[Event], str] | None = None

    def class_of(self, event: Event) -> str:
        return self.classify(event) if self.classify else self.cls


def uses(ctx: Context, activity: str, *entities: str | None) -> None:
    for entity in entities:
        if entity:
            ctx.graph.link(activity, "prov:used", entity)


def generated(ctx: Context, activity: str, entity: str, event: Event) -> str:
    """`entity` was generated by `activity` and attributed to the principal it acted for."""
    ctx.graph.put(
        entity,
        prov__wasGeneratedBy=ref(activity),
        prov__wasAttributedTo=ref(ctx.graph.principal(event["acted_for"])),
    )
    return entity


def invalidated(ctx: Context, activity: str, entity: str | None, event: Event) -> None:
    if entity:
        ctx.graph.put(entity, prov__wasInvalidatedBy=ref(activity))


def conversation(conversation_id: str) -> str:
    return uuid_iri(conversation_id)
