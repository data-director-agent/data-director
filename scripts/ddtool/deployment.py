PRIVACY_NOTICE_VARIABLE = "DD_PRIVACY_NOTICE_URL"
GENERATED = "# Generated by `dd.py apply` from deployment.yaml; edit that file, not this one."
SERVICE_GROUP = "datadirector"  # deploy/install.sh's service user and group
MODEL_KEY = "anthropic-api-key"
TOOL = "sudo data-director"  # the command on a VM


# --- What apply writes -------------------------------------------------------------------------


def agent_id(name: str) -> str:
    """The agent id a profile names for an agents.yaml name (`advisor-dmp` -> `advisor.dmp`)."""
    return name.replace("-", ".", 1)


# The keys `apply` sets itself. Every other key of the release's profile example reaches the
# generated profile as the example has it, so a key added to the example is not lost.
OWNED_PROFILE_KEYS = frozenset(
    {
        "profile_id",
        "version",
        "description",
        "agents",
        "orchestrator",
        "model_accounts",  # from deployment.yaml; the example's own is not carried
        "institution_repositories",  # from deployment.yaml, as the instance's own institution's
        "tool_servers",  # from the PID resolver
    }
)
LIST_PROFILE_KEYS = ("actions_requiring_approval", "hosted_models")


def _carried(base: dict[str, Any], disabled: set[str]) -> dict[str, Any]:
    """The example's keys that `apply` does not set: the profile's other policy. `agent_settings`
    for an agent the profile no longer enables is left out, as the app would refuse the profile."""
    carried = {k: v for k, v in base.items() if k not in OWNED_PROFILE_KEYS}
    carried.setdefault("actions_requiring_approval", [])
    for key in LIST_PROFILE_KEYS:
        if key in carried:
            carried[key] = list(carried[key] or [])
    if isinstance(carried.get("agent_settings"), dict):
        carried["agent_settings"] = {
            k: v for k, v in carried["agent_settings"].items() if str(k) not in disabled
        }
    return carried


def profile(
    deployment: Deployment,
    example: Path,
    current: str | None,
    tool_servers: dict[str, list[str]] | None = None,
) -> str:
    """The generated profile's text. `current` is the profile as it stands, if there is one;
    `tool_servers` are the MCP servers granted (ddtool.pid_resolver)."""
    base: dict[str, Any] = yaml.safe_load(example.read_text(encoding="utf-8")) or {}
    disabled = {agent_id(name) for name in deployment.disabled}
    body: dict[str, Any] = {
        "profile_id": f"{base.get('profile_id', 'data-director-app')}-{deployment.name}",
        "version": 0,
        "description": f"{base.get('description', '')} Deployment {deployment.name}.".strip(),
        "agents": {k: v for k, v in dict(base.get("agents") or {}).items() if k not in disabled},
        "orchestrator": f"orchestrator.{deployment.orchestrator}",
        **_carried(base, disabled),
    }
    if deployment.model_accounts is not None:
        body["model_accounts"] = deployment.model_accounts
    if deployment.institution_repositories:
        body["institution_repositories"] = deployment.institution_repositories
    if tool_servers:
        body["tool_servers"] = tool_servers
    have: dict[str, Any] = (yaml.safe_load(current) or {}) if current else {}
    base_version = int(base.get("version") or 1)
    have_version = int(have.get("version") or 0) if isinstance(have, dict) else 0
    if isinstance(have, dict) and {**have, "version": 0} == body:
        body["version"] = have_version  # unchanged: keep its version
    else:
        body["version"] = max(have_version, base_version) + 1
    return f"{GENERATED}\n" + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def target_dropin(running: list[Agent]) -> str:
    wants = "".join(f"Wants={agent_unit(a.name)}\n" for a in running)
    return f"{GENERATED}\n[Unit]\n{wants}"


def app_dropin(running: list[Agent]) -> str:
    after = "".join(f"After={agent_unit(a.name)}\n" for a in running)
    ports = " ".join(str(a.port) for a in running)
    return f'{GENERATED}\n[Unit]\n{after}\n[Service]\nEnvironment="DD_WAIT_PORTS={ports}"\n'


@dataclass(frozen=True)
class Write:
    path: Path
    text: str
    mode: int
    group: str | None = None  # None: the owner's own group


@dataclass
class Plan:
    """What `apply` would change: files to write and units to stop."""

    writes: list[Write] = field(default_factory=list)
    # app.env and the settings it should hold: a value to set, or None to remove the variable.
    app_env: tuple[Path, dict[str, str | None]] | None = None
    stop: list[str] = field(default_factory=list)
    refusals: list[str] = field(default_factory=list)
    # Credentials drop-ins that deploy/credentials.sh would rewrite, as short phrases.
    credentials: list[str] = field(default_factory=list)

    def pending(self, system: System) -> list[str]:
        """Each change not yet made, as a short phrase. A file this user may not read is left
        out, as whether it differs cannot be told."""
        found = [
            f"{shown(w.path)}"
            for w in self.writes
            if not system.exists(w.path)
            or (system.readable(w.path) and system.read(w.path) != w.text)
        ]
        if self.app_env is not None:
            env_file, settings = self.app_env
            if system.readable(env_file):
                have = read_env(env_file)
                found += [
                    f"{name} in {shown(env_file)}"
                    for name, value in settings.items()
                    if have.get(name) != value
                ]
        found += self.credentials
        found += [f"stop {unit}" for unit in self.stop]
        return found


@dataclass(frozen=True)
class Place:
    """Where an instance's configuration lives: development's `config/local/` or a VM's."""

    etc: Path
    source: Path  # the release (or checkout) whose agents.yaml and profile example apply
    unit_dir: Path | None = None  # None in development: no systemd

    @property
    def deployment(self) -> Path:
        return self.etc / "deployment.yaml"

    @property
    def profile(self) -> Path:
        return self.etc / "profile.yaml"

    @property
    def app_env(self) -> Path:
        return self.etc / "app.env"

    @staticmethod
    def dev() -> Place:
        return Place(paths.LOCAL_DIR, paths.ROOT)

    @staticmethod
    def vm(vm: Vm) -> Place:
        return Place(vm.etc, vm.source(), vm.unit_dir)


def has_key(system: System, place: Place, vm: Vm | None, name: str) -> bool:
    """Whether agent `name` has its model key where it will look."""
    if place.unit_dir is None:
        own = read_env(paths.AGENT_ENV_DIR / f"{name}.env")
        if own.get("ANTHROPIC_API_KEY"):
            return True
        file = own.get("ANTHROPIC_API_KEY_FILE")
        return file is not None and (paths.CREDENTIALS_DIR / file).is_file()
    assert vm is not None
    return vm_model_access(system, vm, name).key


def _local_key_refusal(system: System, place: Place, agent: Agent) -> str | None:
    if agent.name in MODEL_BACKED and not has_key(system, place, None, agent.name):
        return (
            f"{agent.name} calls a model and has no key; first: "
            f"uv run scripts/dd.py secret set {agent.name} {MODEL_KEY}"
        )
    return None


def key_refusal(system: System, place: Place, vm: Vm | None, agent: Agent) -> str | None:
    """Why `apply` will not turn on `agent` for want of its model credentials; None if it has them
    or calls no model. On a VM, an agent that calls through the model broker needs its broker
    credential and no provider key in place of a key (ddtool.model_access)."""
    if place.unit_dir is None:
        return _local_key_refusal(system, place, agent)
    assert vm is not None
    own = read_settings(system, vm.agent_env(agent.name)) or {}
    # Locally, `start` turns a model that is on by default off; on a VM it stays on.
    if agent.name not in MODEL_BACKED and not model_on_by_default(agent.name, own):
        return None
    access = vm_model_access(system, vm, agent.name)
    if access.brokered:
        problem = access.broker_problem(agent.name, TOOL)
        return None if problem is None else f"{problem[0]}; first: {problem[1]}"
    if access.key:
        return None
    fix = f"{TOOL} secret set {agent.name} {access.provider_file}"
    if agent.name in MODEL_BACKED:
        return f"{agent.name} calls a model and has no key; first: {fix}"
    return (
        f"{agent.name} calls a model by default and has no key; first: {fix}, or set "
        f"{MODEL_BY_DEFAULT[agent.name]}=template in {vm.agent_env(agent.name)}"
    )


def plan(system: System, place: Place, vm: Vm | None = None) -> tuple[Deployment, Plan]:
    agents = load_agents(place.source / "app" / "config" / "agents.yaml")
    if not place.deployment.is_file():
        raise DevError(
            f"no {shown(place.deployment)}; copy config/examples/deployment.yaml there and edit it"
        )
    deployment = load(place.deployment, agents)
    running = deployment.runs(agents)
    result = Plan()
    current = system.read(place.profile) if system.readable(place.profile) else None
    example = place.source / "app" / "config" / "profile.yaml.example"
    on_vm = place.unit_dir is not None
    pid = pid_resolver.settings(
        on=deployment.pid_resolver, disabled=deployment.disabled, source=place.source, on_vm=on_vm
    )
    group = SERVICE_GROUP if on_vm else None
    result.writes.append(
        Write(place.profile, profile(deployment, example, current, pid.tool_servers), 0o640, group)
    )
    if pid.refusal:
        result.refusals.append(pid.refusal)
    listed_names = [agent.name for agent in agents]
    brokered = (
        brokered_on_vm(system, vm, listed_names)
        if vm is not None and on_vm
        else brokered_locally(listed_names)
    )
    listed = place.etc / FILE_NAME
    release_list = place.source / "app" / "config" / FILE_NAME
    result.writes.append(Write(listed, agent_list(release_list, brokered, GENERATED), 0o640, group))
    result.app_env = (
        place.app_env,
        {
            "DD_PROFILE": str(place.profile),
            AGENTS_CONFIG_VARIABLE: str(listed),
            PRIVACY_NOTICE_VARIABLE: deployment.privacy_notice,
            pid_resolver.TOOLS_CONFIG_VARIABLE: pid.tools_config,
        },
    )
    for agent in running:
        if refusal := key_refusal(system, place, vm, agent):
            result.refusals.append(refusal)
    result.refusals += broker_refusals(
        system, vm if on_vm else None, deployment.model_accounts, running, brokered
    )
    if on_vm:
        assert place.unit_dir is not None
        result.writes.append(
            Write(
                place.unit_dir / "data-director.target.d" / "agents.conf",
                target_dropin(running),
                0o644,
            )
        )
        # The workbench reaches the same agents as the app, so it waits for the same ones.
        for unit in ("data-director-app", "data-director-workbench"):
            result.writes.append(
                Write(
                    place.unit_dir / f"{unit}.service.d" / "agents.conf",
                    app_dropin(running),
                    0o644,
                )
            )
        assert vm is not None
        if grants := app_model_grants_pending(system, vm):
            result.credentials.append(grants)
        names = {a.name for a in running}
        result.stop = [
            unit
            for unit in agent_instances(system)
            if unit.removeprefix("data-director-agent@").removesuffix(".service") not in names
            and is_active(system, unit)
        ]
    return deployment, result


# --- apply -------------------------------------------------------------------------------------


def _write(write: Write) -> None:
    write.path.parent.mkdir(parents=True, exist_ok=True)
    tmp = write.path.with_name(f".{write.path.name}.tmp")
    tmp.write_text(write.text, encoding="utf-8")
    tmp.chmod(write.mode)
    if write.group is not None and os.geteuid() == 0:
        os.chown(tmp, 0, grp.getgrnam(write.group).gr_gid)
    tmp.replace(write.path)


def _set_app_settings(env_file: Path, settings: dict[str, str | None]) -> None:
    """Set each of `settings` in app.env, removing those whose value is None, and keep the file's
    mode and owner (the app's group reads it)."""
    before = env_file.stat() if env_file.exists() else None
    update_env(
        env_file,
        {name: value for name, value in settings.items() if value is not None},
        "# The app's settings (docs/guide/operations/configuration.md).",
    )
    remove_env(env_file, [name for name, value in settings.items() if value is None])
    if before is not None:
        env_file.chmod(before.st_mode & 0o777)
        if os.geteuid() == 0:
            os.chown(env_file, before.st_uid, before.st_gid)


def apply(system: System, place: Place, vm: Vm | None = None, *, check: bool = False) -> int:
    deployment, result = plan(system, place, vm)
    print(
        f"deployment {deployment.name}: orchestrator {deployment.orchestrator}"
        + (f", disabled {', '.join(sorted(deployment.disabled))}" if deployment.disabled else "")
        + (f", privacy notice {deployment.privacy_notice}" if deployment.privacy_notice else "")
    )
    for refusal in result.refusals:
        print(f"refused: {refusal}")
    if result.refusals:
        return 1
    pending = result.pending(system)
    if check or not pending:
        for item in pending:
            print(f"would change: {item}")
        print("Nothing to change." if not pending else f"{len(pending)} change(s) to apply.")
        return 1 if (check and pending) else 0
    if place.unit_dir is not None and not system.is_root():
        raise DevError("apply changes systemd units: run it as root (sudo data-director apply)")
    _write_changes(result)
    if place.unit_dir is None:
        print("Restart `dd.py start` for the app to read it.")
        return 0
    assert vm is not None
    return _reload_units(system, place, vm, result)


def _write_changes(result: Plan) -> None:
    """Write each file that differs from the plan, and set the app's settings that do."""
    for write in result.writes:
        if not write.path.is_file() or write.path.read_text(encoding="utf-8") != write.text:
            _write(write)
            print(f"wrote {shown(write.path)}")
    if result.app_env is not None:
        env_file, settings = result.app_env
        have = read_env(env_file)
        if changed := [name for name, value in settings.items() if have.get(name) != value]:
            _set_app_settings(env_file, settings)
            print(f"set {', '.join(changed)} in {shown(env_file)}")


def _reload_units(system: System, place: Place, vm: Vm, result: Plan) -> int:
    """On a VM: sync the agents' credentials, reload systemd, stop the units the plan drops and
    restart the stack. 1 if the credentials did not sync."""
    sync = system.run(
        "env",
        f"CREDENTIALS={vm.credentials}",
        f"UNIT_DIR={place.unit_dir}",
        f"AGENTS_DIR={place.source / 'deploy' / 'agents'}",
        "bash",
        "-c",
        'source "$0"; sync_all_credentials',
        str(vm.clone / "deploy" / "credentials.sh"),
    )
    if sync.out.strip():
        print(sync.out.strip())
    system.run("systemctl", "daemon-reload")
    for unit in result.stop:
        system.run("systemctl", "disable", "--now", unit)
        print(f"stopped {unit}")
    if is_active(system, "data-director.target"):
        system.run("systemctl", "restart", "data-director.target")
        print("restarted data-director.target")
    return 0 if sync.status == 0 else 1
