"""`deployment.yaml`, the one file that says what an instance runs, and `dd.py apply`, which makes
the instance so.

    name: datadir-dev        # names the generated profile
    orchestrator: model      # the agent the home page converses with: model or stub
    disabled: []             # agents in app/config/agents.yaml not to run

From it and the release's `app/config/agents.yaml` and `profile.yaml.example`, `apply` writes:

- the profile, `profile.yaml` beside `deployment.yaml`, with `DD_PROFILE` naming it in
  `app.env`. Its `version` rises whenever its content changes, so each stored run names the
  rules it ran under (docs/guide/operations/configuration.md);
- on a VM, the drop-ins that make `data-director.target` start each agent that runs and the app
  wait for them (`After=` and `DD_WAIT_PORTS`), and each agent's credentials drop-in
  (deploy/credentials.sh). It stops and disables any agent unit that no longer runs.

Agent settings stay in `agents/<name>.env` and secrets in `credentials/`: this file says only
what runs. A model-backed agent runs only as the orchestrator, and `apply` refuses to turn one on
without its key.
"""

from __future__ import annotations

import grp
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from ddtool import paths
from ddtool.common import MODEL_BACKED, Agent, DevError, load_agents, read_env, shown, update_env
from ddtool.vm import System, Vm, agent_instances, agent_unit, is_active, loaded_secrets

ORCHESTRATORS = ("model", "stub")
KEYS = {"name", "orchestrator", "disabled"}
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
GENERATED = "# Generated by `dd.py apply` from deployment.yaml; edit that file, not this one."
SERVICE_GROUP = "datadirector"  # deploy/install.sh's service user and group
MODEL_KEY = "anthropic-api-key"


@dataclass(frozen=True)
class Deployment:
    name: str
    orchestrator: str
    disabled: frozenset[str] = frozenset()

    @property
    def orchestrator_agent(self) -> str:
        """The orchestrator's name in agents.yaml (its id with `-` for `.`)."""
        return f"orchestrator-{self.orchestrator}"

    def runs(self, agents: list[Agent]) -> list[Agent]:
        """The agents this instance runs: every listed agent but those disabled, and a
        model-backed one only as the orchestrator."""
        return [
            agent
            for agent in agents
            if agent.name not in self.disabled
            and (agent.name not in MODEL_BACKED or agent.name == self.orchestrator_agent)
        ]


def load(path: Path, agents: list[Agent]) -> Deployment:
    """`path`'s deployment, checked against the agents the release lists."""
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as exc:
        raise DevError(f"{shown(path)} is not valid YAML: {exc}") from exc
    if not isinstance(data, dict):
        raise DevError(f"{shown(path)}: expected name, orchestrator and disabled")
    if unknown := sorted(set(data) - KEYS):
        raise DevError(
            f"{shown(path)}: unknown key {', '.join(unknown)} (known: {', '.join(sorted(KEYS))})"
        )
    name = str(data.get("name") or "")
    if not NAME.match(name):
        raise DevError(
            f"{shown(path)}: name is lower-case words joined by hyphens, such as datadir-dev"
        )
    orchestrator = str(data.get("orchestrator") or "stub")
    if orchestrator not in ORCHESTRATORS:
        raise DevError(
            f"{shown(path)}: orchestrator is {' or '.join(ORCHESTRATORS)}, not {orchestrator!r}"
        )
    disabled = data.get("disabled") or []
    if not isinstance(disabled, list):
        raise DevError(f"{shown(path)}: disabled is a list of agent names")
    known = {agent.name for agent in agents}
    if unknown_agents := sorted(set(map(str, disabled)) - known):
        raise DevError(
            f"{shown(path)}: disabled names {', '.join(unknown_agents)}, not in agents.yaml"
        )
    found = Deployment(name, orchestrator, frozenset(map(str, disabled)))
    if found.orchestrator_agent not in known:
        raise DevError(f"{shown(path)}: agents.yaml lists no {found.orchestrator_agent}")
    if found.orchestrator_agent in found.disabled:
        raise DevError(f"{shown(path)}: the orchestrator, {found.orchestrator_agent}, is disabled")
    return found


# --- What apply writes -------------------------------------------------------------------------


def agent_id(name: str) -> str:
    """The agent id a profile names for an agents.yaml name (`advisor-dmp` -> `advisor.dmp`)."""
    return name.replace("-", ".", 1)


def profile(deployment: Deployment, example: Path, current: str | None) -> str:
    """The generated profile's text. `current` is the profile as it stands, if there is one."""
    base: dict[str, Any] = yaml.safe_load(example.read_text(encoding="utf-8")) or {}
    disabled = {agent_id(name) for name in deployment.disabled}
    body: dict[str, Any] = {
        "profile_id": f"{base.get('profile_id', 'data-director-app')}-{deployment.name}",
        "version": 0,
        "description": f"{base.get('description', '')} Deployment {deployment.name}.".strip(),
        "agents": {k: v for k, v in dict(base.get("agents") or {}).items() if k not in disabled},
        "orchestrator": f"orchestrator.{deployment.orchestrator}",
        "actions_requiring_approval": list(base.get("actions_requiring_approval") or []),
    }
    have: dict[str, Any] = (yaml.safe_load(current) or {}) if current else {}
    base_version = int(base.get("version") or 1)
    have_version = int(have.get("version") or 0) if isinstance(have, dict) else 0
    if isinstance(have, dict) and {**have, "version": 0} == body:
        body["version"] = have_version  # unchanged: keep its version
    else:
        body["version"] = max(have_version, base_version) + 1
    return f"{GENERATED}\n" + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def target_dropin(running: list[Agent]) -> str:
    wants = "".join(f"Wants={agent_unit(a.name)}\n" for a in running)
    return f"{GENERATED}\n[Unit]\n{wants}"


def app_dropin(running: list[Agent]) -> str:
    after = "".join(f"After={agent_unit(a.name)}\n" for a in running)
    ports = " ".join(str(a.port) for a in running)
    return f'{GENERATED}\n[Unit]\n{after}\n[Service]\nEnvironment="DD_WAIT_PORTS={ports}"\n'


@dataclass(frozen=True)
class Write:
    path: Path
    text: str
    mode: int
    group: str | None = None  # None: the owner's own group


@dataclass
class Plan:
    """What `apply` would change: files to write and units to stop."""

    writes: list[Write] = field(default_factory=list)
    app_env: tuple[Path, str] | None = None  # app.env and the DD_PROFILE it should hold
    stop: list[str] = field(default_factory=list)
    refusals: list[str] = field(default_factory=list)

    def pending(self, system: System) -> list[str]:
        """Each change not yet made, as a short phrase. A file this user may not read is left
        out, as whether it differs cannot be told."""
        found = [
            f"{shown(w.path)}"
            for w in self.writes
            if not system.exists(w.path)
            or (system.readable(w.path) and system.read(w.path) != w.text)
        ]
        if self.app_env is not None:
            env_file, value = self.app_env
            if system.readable(env_file) and read_env(env_file).get("DD_PROFILE") != value:
                found.append(f"DD_PROFILE in {shown(env_file)}")
        found += [f"stop {unit}" for unit in self.stop]
        return found


@dataclass(frozen=True)
class Place:
    """Where an instance's configuration lives: development's `config/local/` or a VM's."""

    etc: Path
    source: Path  # the release (or checkout) whose agents.yaml and profile example apply
    unit_dir: Path | None = None  # None in development: no systemd

    @property
    def deployment(self) -> Path:
        return self.etc / "deployment.yaml"

    @property
    def profile(self) -> Path:
        return self.etc / "profile.yaml"

    @property
    def app_env(self) -> Path:
        return self.etc / "app.env"

    @staticmethod
    def dev() -> Place:
        return Place(paths.LOCAL_DIR, paths.ROOT)

    @staticmethod
    def vm(vm: Vm) -> Place:
        return Place(vm.etc, vm.source(), vm.unit_dir)


def has_key(system: System, place: Place, vm: Vm | None, name: str) -> bool:
    """Whether agent `name` has its model key where it will look."""
    if place.unit_dir is None:
        own = read_env(paths.AGENT_ENV_DIR / f"{name}.env")
        if own.get("ANTHROPIC_API_KEY"):
            return True
        file = own.get("ANTHROPIC_API_KEY_FILE")
        return file is not None and (paths.CREDENTIALS_DIR / file).is_file()
    assert vm is not None
    stored = vm.credentials / name / MODEL_KEY
    if system.is_root():
        return stored.is_file() and stored.stat().st_size > 0
    return MODEL_KEY in loaded_secrets(system, vm, name)


def plan(system: System, place: Place, vm: Vm | None = None) -> tuple[Deployment, Plan]:
    agents = load_agents(place.source / "app" / "config" / "agents.yaml")
    if not place.deployment.is_file():
        raise DevError(
            f"no {shown(place.deployment)}; copy config/examples/deployment.yaml there and edit it"
        )
    deployment = load(place.deployment, agents)
    running = deployment.runs(agents)
    result = Plan()
    current = system.read(place.profile) if system.readable(place.profile) else None
    example = place.source / "app" / "config" / "profile.yaml.example"
    on_vm = place.unit_dir is not None
    group = SERVICE_GROUP if on_vm else None
    result.writes.append(Write(place.profile, profile(deployment, example, current), 0o640, group))
    result.app_env = (place.app_env, str(place.profile))
    for agent in running:
        if agent.name in MODEL_BACKED and not has_key(system, place, vm, agent.name):
            tool = "sudo data-director" if on_vm else "uv run scripts/dd.py"
            result.refusals.append(
                f"{agent.name} calls a model and has no key; first: "
                f"{tool} secret set {agent.name} {MODEL_KEY}"
            )
    if on_vm:
        assert place.unit_dir is not None
        result.writes.append(
            Write(
                place.unit_dir / "data-director.target.d" / "agents.conf",
                target_dropin(running),
                0o644,
            )
        )
        result.writes.append(
            Write(
                place.unit_dir / "data-director-app.service.d" / "agents.conf",
                app_dropin(running),
                0o644,
            )
        )
        names = {a.name for a in running}
        result.stop = [
            unit
            for unit in agent_instances(system)
            if unit.removeprefix("data-director-agent@").removesuffix(".service") not in names
            and is_active(system, unit)
        ]
    return deployment, result


# --- apply -------------------------------------------------------------------------------------


def _write(write: Write) -> None:
    write.path.parent.mkdir(parents=True, exist_ok=True)
    tmp = write.path.with_name(f".{write.path.name}.tmp")
    tmp.write_text(write.text, encoding="utf-8")
    tmp.chmod(write.mode)
    if write.group is not None and os.geteuid() == 0:
        os.chown(tmp, 0, grp.getgrnam(write.group).gr_gid)
    tmp.replace(write.path)


def _set_profile(env_file: Path, value: str) -> None:
    """Set DD_PROFILE in app.env, keeping the file's mode and owner (the app's group reads it)."""
    before = env_file.stat() if env_file.exists() else None
    update_env(
        env_file,
        {"DD_PROFILE": value},
        "# The app's settings (docs/guide/operations/configuration.md).",
    )
    if before is not None:
        env_file.chmod(before.st_mode & 0o777)
        if os.geteuid() == 0:
            os.chown(env_file, before.st_uid, before.st_gid)


def apply(system: System, place: Place, vm: Vm | None = None, check: bool = False) -> int:
    deployment, result = plan(system, place, vm)
    print(
        f"deployment {deployment.name}: orchestrator {deployment.orchestrator}"
        + (f", disabled {', '.join(sorted(deployment.disabled))}" if deployment.disabled else "")
    )
    for refusal in result.refusals:
        print(f"refused: {refusal}")
    if result.refusals:
        return 1
    pending = result.pending(system)
    if check or not pending:
        for item in pending:
            print(f"would change: {item}")
        print("Nothing to change." if not pending else f"{len(pending)} change(s) to apply.")
        return 1 if (check and pending) else 0
    if place.unit_dir is not None and not system.is_root():
        raise DevError("apply changes systemd units: run it as root (sudo data-director apply)")
    for write in result.writes:
        if not write.path.is_file() or write.path.read_text(encoding="utf-8") != write.text:
            _write(write)
            print(f"wrote {shown(write.path)}")
    if result.app_env is not None:
        env_file, value = result.app_env
        if read_env(env_file).get("DD_PROFILE") != value:
            _set_profile(env_file, value)
            print(f"set DD_PROFILE in {shown(env_file)}")
    if place.unit_dir is None:
        print("Restart `dd.py start` for the app to read it.")
        return 0
    assert vm is not None
    sync = system.run(
        "env",
        f"CREDENTIALS={vm.credentials}",
        f"UNIT_DIR={place.unit_dir}",
        f"AGENTS_DIR={place.source / 'deploy' / 'agents'}",
        "bash",
        "-c",
        'source "$0"; sync_all_credentials',
        str(vm.clone / "deploy" / "credentials.sh"),
    )
    if sync.out.strip():
        print(sync.out.strip())
    system.run("systemctl", "daemon-reload")
    for unit in result.stop:
        system.run("systemctl", "disable", "--now", unit)
        print(f"stopped {unit}")
    if is_active(system, "data-director.target"):
        system.run("systemctl", "restart", "data-director.target")
        print("restarted data-director.target")
    return 0 if sync.status == 0 else 1
